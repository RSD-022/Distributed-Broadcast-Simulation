#!/usr/bin/env python3
"""Generate synthetic topologies for the Diffuse-v3 experiments (Step 4).

For each (family, n, seed) it writes:
  simulations/synthetic/<Name>.ned          NED network (package synthetic)
  data/topologies/synthetic/<Name>.edges    one "u v" pair per line, u < v
and updates one row in data/topologies/manifest.csv.

Usage (from anywhere):
  python3 scripts/generate_topologies.py --family ring --n 10 --seed 1
  python3 scripts/generate_topologies.py --all          # 6 families x 4 sizes
"""
import argparse
import csv
import hashlib
import math
import sys
from pathlib import Path

import networkx as nx

ROOT = Path(__file__).resolve().parents[1]
NED_DIR = ROOT / "simulations" / "synthetic"
EDGE_DIR = ROOT / "data" / "topologies" / "synthetic"
MANIFEST = ROOT / "data" / "topologies" / "manifest.csv"
FIELDS = ["name", "family", "n", "m", "avg_degree", "diameter", "seed", "source", "sha256"]

FAMILIES = ["line", "ring", "tree", "grid", "complete", "random"]
SIZES = [10, 20, 50, 100]
PREFIX = {"line": "Line", "ring": "Ring", "tree": "Tree", "grid": "Grid",
          "complete": "Complete", "random": "Random"}


def grid_shape(n):
    """Most square factorisation rows x cols of n (10 -> 2x5, 100 -> 10x10)."""
    r = int(math.isqrt(n))
    while n % r:
        r -= 1
    return r, n // r


def build(family, n, seed):
    """Return (edge set of (u, v) with u < v, source description)."""
    if family == "line":
        edges = {(i, i + 1) for i in range(n - 1)}
        return edges, "path graph"
    if family == "ring":
        edges = {tuple(sorted((i, (i + 1) % n))) for i in range(n)}
        return edges, "cycle graph"
    if family == "tree":
        # complete binary tree with n nodes: parent of i is (i-1)//2
        edges = {((i - 1) // 2, i) for i in range(1, n)}
        return edges, "complete binary tree"
    if family == "grid":
        r, c = grid_shape(n)
        edges = set()
        for i in range(r):
            for j in range(c):
                u = i * c + j
                if j + 1 < c:
                    edges.add((u, u + 1))
                if i + 1 < r:
                    edges.add((u, u + c))
        return edges, f"grid {r}x{c}"
    if family == "complete":
        edges = {(u, v) for u in range(n) for v in range(u + 1, n)}
        return edges, "complete graph"
    if family == "random":
        p = min(1.0, 2 * math.log(n) / n)  # above the connectivity threshold ln(n)/n
        for attempt in range(1, 1001):
            g = nx.gnp_random_graph(n, p, seed=seed + attempt - 1)
            if nx.is_connected(g):
                edges = {tuple(sorted(e)) for e in g.edges()}
                return edges, f"G(n,p) p={p:.4f} attempts={attempt}"
        raise RuntimeError("no connected G(n,p) graph found in 1000 attempts")
    raise ValueError(f"unknown family {family}")


def validate(edges, n):
    """Reject self-loops / duplicates / bad ids, check connectivity."""
    seen = set()
    for u, v in edges:
        if u == v:
            raise ValueError(f"self-loop on node {u}")
        if not (0 <= u < n and 0 <= v < n):
            raise ValueError(f"edge ({u},{v}) outside 0..{n-1}")
        key = (min(u, v), max(u, v))
        if key in seen:
            raise ValueError(f"duplicate edge {key}")
        seen.add(key)
    g = nx.Graph()
    g.add_nodes_from(range(n))
    g.add_edges_from(seen)
    if not nx.is_connected(g):
        raise ValueError("graph is not connected")
    return g


def write_ned(path, name, n, edges):
    lines = [
        "package synthetic;",
        "",
        "import Node3;",
        "import Link;",
        "",
        f"// Generated by scripts/generate_topologies.py. Do not edit by hand.",
        f"network {name}",
        "{",
        "    submodules:",
        f"        node[{n}]: Node3;",
        "    connections:",
    ]
    for u, v in edges:
        lines.append(f"        node[{u}].gate++ <--> Link <--> node[{v}].gate++;")
    lines += ["}", ""]
    path.write_bytes("\n".join(lines).encode())  # bytes: same LF endings on every OS


def update_manifest(row):
    rows = {}
    if MANIFEST.exists():
        with MANIFEST.open(newline="") as f:
            for r in csv.DictReader(f):
                rows[r["name"]] = r
    rows[row["name"]] = {k: str(v) for k, v in row.items()}
    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    with MANIFEST.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS, lineterminator="\n")
        w.writeheader()
        for name in sorted(rows):
            w.writerow(rows[name])


def generate(family, n, seed):
    name = f"{PREFIX[family]}{n}"
    edges, source = build(family, n, seed)
    g = validate(edges, n)
    edges = sorted(edges)

    NED_DIR.mkdir(parents=True, exist_ok=True)
    EDGE_DIR.mkdir(parents=True, exist_ok=True)
    write_ned(NED_DIR / f"{name}.ned", name, n, edges)
    edge_bytes = "".join(f"{u} {v}\n" for u, v in edges).encode()
    (EDGE_DIR / f"{name}.edges").write_bytes(edge_bytes)

    m = len(edges)
    update_manifest({
        "name": name, "family": family, "n": n, "m": m,
        "avg_degree": f"{2 * m / n:.3f}",
        "diameter": nx.diameter(g),
        "seed": seed if family == "random" else "",
        "source": source,
        "sha256": hashlib.sha256(edge_bytes).hexdigest(),
    })
    print(f"{name}: n={n} m={m} diameter={nx.diameter(g)} ({source})")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--family", choices=FAMILIES)
    ap.add_argument("--n", type=int)
    ap.add_argument("--seed", type=int, default=1, help="only used by the random family")
    ap.add_argument("--all", action="store_true", help="all families x sizes 10,20,50,100")
    a = ap.parse_args()
    if a.all:
        for fam in FAMILIES:
            for n in SIZES:
                generate(fam, n, a.seed)
    elif a.family and a.n:
        generate(a.family, a.n, a.seed)
    else:
        ap.error("give --family and --n, or --all")


if __name__ == "__main__":
    sys.exit(main())
